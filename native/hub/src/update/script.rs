//! Renders the small platform scripts that replace the installation after the
//! app exits. Rendering is pure text generation so every variant is testable
//! on any host.

use std::path::{Path, PathBuf};

#[derive(Debug, Clone)]
pub(crate) struct ScriptPlan {
    /// Script output; kept after the update for diagnosis.
    pub log: PathBuf,
    /// Update workspace (download and staged payload); removed on success.
    pub workspace: PathBuf,
    /// What replaces `target`: the extracted install directory (Windows), the
    /// AppImage (Linux), or the `YAAS.app` bundle (macOS).
    pub staged: PathBuf,
    /// Install directory (Windows), AppImage path (Linux), or bundle path (macOS).
    pub target: PathBuf,
    /// Application process that must exit before files are replaced.
    pub pid: u32,
    /// Relaunch with `--portable`.
    pub portable: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ScriptKind {
    Windows,
    Linux,
    MacOs,
}

impl ScriptKind {
    pub(crate) fn host() -> Self {
        if cfg!(windows) {
            ScriptKind::Windows
        } else if cfg!(target_os = "macos") {
            ScriptKind::MacOs
        } else {
            ScriptKind::Linux
        }
    }

    pub(crate) fn file_name(self) -> &'static str {
        match self {
            ScriptKind::Windows => "update.bat",
            ScriptKind::Linux | ScriptKind::MacOs => "update.sh",
        }
    }
}

/// Batch files need literal `%` doubled and CRLF line endings.
fn bat_path(path: &Path) -> String {
    path.display().to_string().replace('%', "%%")
}

/// Single-quotes a value for POSIX shells.
fn sh_quote(path: &Path) -> String {
    format!("'{}'", path.display().to_string().replace('\'', r"'\''"))
}

pub(crate) fn render(kind: ScriptKind, plan: &ScriptPlan) -> String {
    match kind {
        ScriptKind::Windows => render_windows(plan),
        ScriptKind::Linux => render_linux(plan),
        ScriptKind::MacOs => render_macos(plan),
    }
}

fn render_windows(plan: &ScriptPlan) -> String {
    let portable = if plan.portable { " --portable" } else { "" };
    let lines = [
        "@echo off".to_string(),
        "setlocal".to_string(),
        format!("set \"PID={}\"", plan.pid),
        format!("set \"SRC={}\"", bat_path(&plan.staged)),
        format!("set \"DST={}\"", bat_path(&plan.target)),
        format!("set \"WORK={}\"", bat_path(&plan.workspace)),
        format!("set \"LOG={}\"", bat_path(&plan.log)),
        String::new(),
        "echo [update] Waiting for YAAS (PID %PID%) to exit... > \"%LOG%\"".to_string(),
        "set /a TRIES=0".to_string(),
        ":wait".to_string(),
        "tasklist /FI \"PID eq %PID%\" /FO CSV /NH 2>nul | findstr /C:\"\\\",\\\"%PID%\\\",\"\" \
         >nul"
            .to_string(),
        "if errorlevel 1 goto exited".to_string(),
        "set /a TRIES+=1".to_string(),
        "if %TRIES% GEQ 20 goto kill".to_string(),
        "ping 127.0.0.1 -n 2 >nul".to_string(),
        "goto wait".to_string(),
        ":kill".to_string(),
        "echo [update] YAAS did not exit; killing >> \"%LOG%\"".to_string(),
        "taskkill /F /PID %PID% >> \"%LOG%\" 2>&1".to_string(),
        "ping 127.0.0.1 -n 3 >nul".to_string(),
        ":exited".to_string(),
        "echo [update] Installing update... >> \"%LOG%\"".to_string(),
        "robocopy \"%SRC%\" \"%DST%\" /E /R:5 /W:1 /NFL /NDL /NP >> \"%LOG%\" 2>&1".to_string(),
        "if errorlevel 8 goto failed".to_string(),
        "rmdir /s /q \"%WORK%\" >nul 2>&1".to_string(),
        "echo [update] Starting new version >> \"%LOG%\"".to_string(),
        format!("start \"\" \"%DST%\\yaas.exe\"{portable}"),
        "(goto) 2>nul & del /f /q \"%~f0\"".to_string(),
        ":failed".to_string(),
        "echo [update] Installation failed >> \"%LOG%\"".to_string(),
        "start \"\" notepad.exe \"%LOG%\"".to_string(),
        "exit /b 1".to_string(),
        String::new(),
    ];
    lines.join("\r\n")
}

/// Shared header and wait-for-exit block for the POSIX scripts.
fn sh_header(plan: &ScriptPlan) -> Vec<String> {
    let mut lines = vec![
        "#!/bin/sh".to_string(),
        "# Generated by YAAS self-update; deletes itself on success.".to_string(),
        format!("PID={}", plan.pid),
        format!("STAGED={}", sh_quote(&plan.staged)),
        format!("TARGET={}", sh_quote(&plan.target)),
        format!("WORK={}", sh_quote(&plan.workspace)),
        format!("exec >{} 2>&1", sh_quote(&plan.log)),
        String::new(),
    ];
    lines.extend(
        [
            "echo \"[update] Waiting for YAAS (PID $PID) to exit...\"",
            "i=0",
            "while kill -0 \"$PID\" 2>/dev/null; do",
            "    i=$((i + 1))",
            "    if [ \"$i\" -ge 150 ]; then",
            "        echo \"[update] YAAS did not exit; killing\"",
            "        kill -9 \"$PID\" 2>/dev/null",
            "        sleep 1",
            "        break",
            "    fi",
            "    sleep 0.2",
            "done",
            "echo \"[update] Installing update\"",
            "NEW=\"$TARGET.yaas-update\"",
        ]
        .map(String::from),
    );
    lines
}

/// Shared tail for the POSIX scripts: cleans up and relaunches on success, or
/// removes the partial copy at `$NEW` on failure.
fn sh_finish(install: &str, relaunch: &str) -> Vec<String> {
    vec![
        format!("if {install}; then"),
        "    rm -rf \"$WORK\"".into(),
        "    rm -f \"$0\"".into(),
        "    echo \"[update] Starting new version\"".into(),
        format!("    {relaunch}"),
        "else".into(),
        "    echo \"[update] FAILED\"".into(),
        "    rm -rf \"$NEW\"".into(),
        "    exit 1".into(),
        "fi".into(),
        String::new(),
    ]
}

fn render_linux(plan: &ScriptPlan) -> String {
    let portable = if plan.portable { " --portable" } else { "" };
    let mut lines = sh_header(plan);
    // The staged AppImage already carries the installed AppImage's permissions.
    lines.extend(sh_finish(
        "cp -p \"$STAGED\" \"$NEW\" && mv -f \"$NEW\" \"$TARGET\"",
        &format!("nohup \"$TARGET\"{portable} </dev/null >/dev/null 2>&1 &"),
    ));
    lines.join("\n")
}

fn render_macos(plan: &ScriptPlan) -> String {
    let mut lines = sh_header(plan);
    lines.push("rm -rf \"$NEW\"".to_string());
    lines.extend(sh_finish(
        "ditto \"$STAGED\" \"$NEW\" && rm -rf \"$TARGET\" && mv \"$NEW\" \"$TARGET\"",
        "open \"$TARGET\"",
    ));
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan() -> ScriptPlan {
        ScriptPlan {
            log: PathBuf::from("/home/user/.local/share/YAAS/updates/update.log"),
            workspace: PathBuf::from("/home/user/.local/share/YAAS/updates/0123 with spaces"),
            staged: PathBuf::from("/home/user/.local/share/YAAS/updates/0123/package"),
            target: PathBuf::from("/home/user/Applications/YAAS App.AppImage"),
            pid: 4242,
            portable: true,
        }
    }

    #[test]
    fn windows_script_replaces_install_dir_and_preserves_portable_flag() {
        let plan = ScriptPlan {
            log: PathBuf::from(r"C:\Users\user\AppData\Local\YAAS\updates\update.log"),
            workspace: PathBuf::from(r"C:\Users\user\AppData\Local\YAAS\updates\0123"),
            staged: PathBuf::from(r"C:\Users\user\AppData\Local\YAAS\updates\0123\new"),
            target: PathBuf::from(r"C:\Users\user\Apps\YAAS"),
            ..plan()
        };
        let script = render(ScriptKind::Windows, &plan);
        assert!(script.contains("set \"PID=4242\""));
        // The wait loop must match the exact PID column of tasklist's CSV output.
        assert!(script.contains(
            "tasklist /FI \"PID eq %PID%\" /FO CSV /NH 2>nul | findstr \
             /C:\"\\\",\\\"%PID%\\\",\"\" >nul"
        ));
        assert!(script.contains("robocopy \"%SRC%\" \"%DST%\" /E /R:5 /W:1"));
        assert!(script.contains("start \"\" \"%DST%\\yaas.exe\" --portable"));
        assert!(script.contains("taskkill /F /PID %PID%"));
        assert!(script.contains("del /f /q \"%~f0\""));
        // Batch files must use CRLF consistently; cmd mis-parses lone LF in some cases.
        assert!(script.contains("\r\n"));
        assert_eq!(script.replace("\r\n", "").matches(['\r', '\n']).count(), 0);
        // No /PURGE: portable data and extra files survive.
        assert!(!script.contains("/PURGE") && !script.contains("/MIR"));
    }

    #[test]
    fn windows_script_escapes_percents_for_batch_parsing() {
        let plan = ScriptPlan { target: PathBuf::from(r"C:\100% legit\YAAS"), ..plan() };
        let script = render(ScriptKind::Windows, &plan);
        assert!(script.contains(r#"set "DST=C:\100%% legit\YAAS""#));
    }

    #[test]
    fn linux_script_replaces_appimage_atomically_and_relaunches() {
        let script = render(ScriptKind::Linux, &plan());
        assert!(script.contains("PID=4242"));
        assert!(script.contains("TARGET='/home/user/Applications/YAAS App.AppImage'"));
        assert!(script.contains("cp -p \"$STAGED\" \"$NEW\" && mv -f \"$NEW\" \"$TARGET\""));
        assert!(script.contains("nohup \"$TARGET\" --portable"));
        assert!(script.contains("kill -9 \"$PID\""));
        assert!(script.contains("rm -f \"$0\""));
        assert!(!script.contains("\r"));
    }

    #[test]
    fn macos_script_swaps_bundle_after_copying() {
        let plan = ScriptPlan {
            staged: PathBuf::from(
                "/Users/user/Library/Application Support/YAAS/updates/0123/new/YAAS.app",
            ),
            target: PathBuf::from("/Applications/YAAS.app"),
            portable: false,
            ..plan()
        };
        let script = render(ScriptKind::MacOs, &plan);
        assert!(script.contains(
            "ditto \"$STAGED\" \"$NEW\" && rm -rf \"$TARGET\" && mv \"$NEW\" \"$TARGET\""
        ));
        assert!(script.contains("open \"$TARGET\""));
        assert!(!script.contains("--portable"));
    }

    #[test]
    fn sh_quote_handles_single_quotes() {
        assert_eq!(sh_quote(Path::new("/a/b'c")), "'/a/b'\\''c'");
    }
}
